/**
 * Generate the Dockerfile of the public plugins image
 * (KONG_PLUGINS_IMAGE): the same base layers as the projects' Kong images
 * (Kong, the OIDC plugin), the framework plugins from the public repo's
 * `kong/plugins/`, and all of them switched on. Nothing else: no config,
 * Kong's own defaults. Built from the assembled repo (writeKongPluginsPackage).
 */

import {
  KONG_OIDC_PLUGIN_NAME,
  KONG_PLUGINS_BUNDLED_KEYWORD,
  KONG_PLUGINS_REPO_URL,
} from '../../constants';
import { buildKongBaseLayers } from './build-kong-base-layers';

export function generateKongPluginsImageDockerfile(params: {
  /** The framework plugins' names */
  plugins: string[];
  version: string;
}): string {
  const kongPlugins = [
    KONG_PLUGINS_BUNDLED_KEYWORD,
    KONG_OIDC_PLUGIN_NAME,
    ...[...params.plugins].sort(),
  ];

  return `# Kong with the tsdevstack plugins and kong-oidc-v3, all switched on.
# Generated by the tsdevstack CLI; see README.md.

${buildKongBaseLayers()}
# The tsdevstack plugins
COPY kong/plugins/ /usr/local/share/lua/5.1/kong/plugins/
COPY LICENSE /usr/local/share/licenses/tsdevstack-kong-plugins/LICENSE

ENV KONG_PLUGINS=${kongPlugins.join(',')}

LABEL org.opencontainers.image.source="${KONG_PLUGINS_REPO_URL}"
LABEL org.opencontainers.image.version="${params.version}"
LABEL org.opencontainers.image.licenses="Apache-2.0"
LABEL org.opencontainers.image.description="Kong with the tsdevstack plugins and kong-oidc-v3"

USER kong
`;
}
